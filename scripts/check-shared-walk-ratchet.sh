# 래칫 상한. **실제 건수와 같아야 한다** — 크면 그 차이만큼 조용히 받아준다.
#
# 2026-09-07 실측 56 (좌변 128 타깃). 이 값의 계보: 2026-09-06 에 레포 전체의
# `read_dir(` 는 131 이고 그중 통합 테스트 타깃의 몫이 57 이었다. 나머지 74 는 이 래칫의
# 대상이 아니다(런타임 파일시스템을 읽는 프로덕션 코드와 순회 도구 자신).
#
# 움직인 이력을 값으로 남긴다 — 이 수가 어느 방향으로 가는지가 계보의 요점이다.
#   59 → 57  두 순회를 공용 헬퍼로 옮겼다.
#   57 → 59  한 회차가 새 순회 둘을 들였다(새 루트 타깃 하나, 기존 파일에 하나).
#   59 → 56  그 둘을 옮기면서, 같은 파일 안에 남아 있던 **같은 디렉토리를 여는 두 번째
#            순회**까지 하나로 합쳤다. 즉 −3 중 하나는 이번 회차의 빚이 아니라
#            원래 있던 중복이다 — 그 자리가 없어졌으므로 상한도 같이 내린다.
#   56 → 55  `crates/tasty-doc-guards/tests/architecture_crate_list_complete.rs` 가
#            크레이트 디렉토리 순회를 lib
#            (`tasty_doc_guards::crate_layers::crate_dir_names`)으로 올려 좌변에서
#            빠졌다. 좌변 파일 수는 안 움직였다.
#   55 → 54  `crates/tasty-doc-guards/tests/adr_index_parity.rs` 의 ADR 디렉토리 순회가
#            lib(`tasty_doc_guards::adr_index::collect`)로 올라갔다 — 인덱스 생성기 bin 과
#            가드가 같은 수집을 쓰게 되면서다. 좌변 파일 수는 안 움직였다.
# 좌변 크기는 `59 → 56` 의 두 측정 사이에 안 움직였다(128 → 128). 그래서 그 감소는
# 좌변이 줄어 안 보이게 된 것이 아니라 순회 자체가 줄어든 것이다. **그 뒤로 좌변은
# 늘었다** — 지금 값은 이 스크립트가 실행마다 첫 줄에 찍는다("통합 테스트 타깃 N개를
# 훑었다"). 그 증가가 새 타깃인지 세는 술어가 넓어진 것인지는 안 갈랐다.
#
# ★ 그래서 지금 **여유가 0 이다** — 건수가 곧 아래 `CAP` 이다. 그 값을 이 문단에
#   복제하지 않는다: 복제본은 상한이 움직일 때마다 낡고, 이 게이트는 그 형태를
#   막으려고 있다. 직접 순회를 하나라도 새로 들이는 변경은 그 자리에서 빨개진다.
#   그것이 이 게이트의 의도이고, 아래 실패문이 옮길 헬퍼를 이름으로 지목한다 —
#   상한을 올려 통과시키는 길은 없다. 여유가 0 이라는 사실 자체를
#   여기 적어 두는 이유는, 안 적으면 처음 걸린 사람이 그것을 결함으로 읽기 때문이다.
#   ★ 그리고 여유 0 이 이 게이트에서 **옳은** 이유는 따로 있다. 여유는 다른 게이트가
#   그 구간을 볼 때만 정당하다(`check-frozen-sum-ratchet.sh` 의 여유가 그 형태다 —
#   그 폭을 파일 크기 게이트가 본다). 직접 순회에는 그런 게이트가 없으므로 여기서
#   여유는 곧 아무도 안 보는 구간이 된다.
#   (그래서 값이 **줄면** 상한도 같이 내린다 — 실측이 내려간 것이지 상한을 만져
#    통과시킨 것이 아니다. 어느 회차에 어느 방향으로 움직였는지는 위 이력에 있다.)
#
# ── 이 값을 고칠 때 함께 움직이는 것 ────────────────────────────────────
# 이 리터럴을 인용하는 자리가 이 파일 밖에도 있다(`tests/shared_walk_gate.rs` 가
# 상한을 바꿔치기하려고 이 줄의 철자를 든다). 그 사본들은
# `crates/tasty-doc-guards/tests/gate_thresholds_are_not_stale_copies.rs` 가 본다 —
# 이 줄만 고치고 사본을 안 고치면 그 가드가 빨개지고 자리를 이름으로 지목한다.
#
# ★ 그 가드가 세는 것은 **값을 낱말로 든 줄**이다. 값을 안 들고 뜻만 말하는 문장
#   ("여유가 0 이다")은 안 본다 — 그래서 위 문단들은 값을 복제하지 않는 쪽을 골랐다.
#   값을 새로 복제하는 자리를 만들면 그 가드의 명부(`SHARED_WALK_CLAIMS`)에 줄 수를
#   함께 올려라. 안 올려도 **조용하지는 않다** — 실측(2026-09-09, 이 트리에서 변이로
#   쟀다): 새 파일이 지금 값을 어휘와 함께 들면 그 가드가 **미분류**로 그 자리에서
#   빨개지고, 이미 명부에 든 파일에 사본이 하나 늘면 **"든 줄이 N 개다(명부 M)"** 로
#   빨개진다. 그러니 명부 갱신은 없던 채널을 만드는 일이 아니라 **이미 빨간 채널을
#   초록으로 되돌리는** 일이다 — 그 차이가 중요한 이유는 아래다.
#   ★ 진짜로 조용한 갈래는 따로 둘이고, 그것이 이 문단이 있어야 할 이유다.
#   (ㄱ) 그 가드의 `EXCLUDED` 에 **이미 든 파일 안에서** 사본이 늘어나는 것 — 제외는
#        파일 단위라 그 파일의 줄 수를 아예 안 센다(그 자리에는 "명부에 줄 수를
#        올려라" 는 위 처방이 애초에 적용되지도 않는다).
#   (ㄴ) **애초에 틀린 값으로 태어난 인용** — 스캔의 좌변이 *지금 값을 든 줄*이라,
#        처음부터 다른 수를 든 문장은 명부에도 제외에도 안 걸린다. 낡아서 틀리는 것이
#        아니라 태어날 때부터 틀린 것이라 대조할 상대가 없다.
#   둘 다 기계가 안 잡는다 — 사람이 읽어야 잡힌다.
CAP=54

# ── 판정기 없이는 **세지도 않는다** ─────────────────────────────────────────
# 폴백(원문에서 세기)은 **더 많이 세는** 방향이라 조용한 통과는 안 만든다. 그런데 래칫은
# 양방향이라 "조용한 통과가 없다" 로 끝나지 않는다 — 값이 상한을 넘으면 실패문이 "상한을
# 올려서 통과시키지 마라" 로 나가고, 그것은 **실재하지 않는 회귀에 대한 처방**이다. 그
# 처방을 따르면 래칫이 영구히 헐거워지고, 되돌릴 사람은 이유를 모른다.
#
# 실측(2026-09-07): rebase 직후 판정기가 낡아 이 게이트가 그 문구로 rc=1 을 냈다. 다른
# lane 이 그 문구를 읽고 상한을 만질 뻔했다. 재빌드 한 줄이면 rc=0 이다.
#
# 그래서 값이 아니라 **판정 가능 여부로 먼저 갈린다 — 좌변을 세기 전에.** 한때는 좌변을
# 다 세고 나서 갈렸다. 그 계수는 이 갈래에서 판정에 안 쓰이므로 순수한 낭비였고, 낭비만도
# 아니었다: **쓰이지 않는 수를 화면에 올리면 누군가 그것을 상한과 견준다.** 그래서 안 쓸
# 수는 안 낸다. 형제 `check-intent-discipline.sh` 가 이미 이 순서다.
#
# 형제 `check-file-size.sh` 와 `check-frozen-sum-ratchet.sh` 도 같은 형태다 — "측정이
# 안 됐으므로 게이트를 통과로 읽지 않는다". 래칫 둘만 그 말을 안 하고 있었다.
if [ "$SCAN_ROOT" = "$ROOT" ]; then
    echo "훑을 통합 테스트 타깃 ${target_count}개 — 세지 않았다."
    echo
    echo "[shared-walk] 판정 불가 — 판정기가 없다(또는 낡았다)."
    echo "  이 상태에서 세면 원문에서 센 값이 나오고, 세는 사본이 다르므로 상한(${CAP})과"
    echo "  견줄 수 없다. 두 값의 차는 회귀의 크기가 아니라 **세는 사본이 바뀐 폭**이다."
    echo
    echo "  ★ 상한을 만지지 마라. 판정기를 지어라:"
    echo "      cargo build -p tasty-doc-guards --bin mask-source"
    echo "      target/debug/mask-source --check-fresh ."
    echo "  --check-fresh 가 rc=0 이어야 이 게이트의 값이 값이다(낡은 판정기도 없는 것으로 다룬다)."
    echo "  rebase 직후라면 이것이 첫 번째로 할 일이다."
    exit 2
fi

report=""
count=0

while IFS= read -r file; do
    [ -z "$file" ] && continue
    # 사본에 없는 파일은 **그 파일만** 원문에서 센다 — 건너뛰면 모수가 조용히 줄고,
    # 줄어든 모수는 언제나 초록이다.
    scan="$SCAN_ROOT/$file"
    [ -f "$scan" ] || scan="$file"
    # `|| true` 로 rc 만 삼킨다 — 없는 것과 못 센 것을 같은 0 으로 만들지 않으려면
    # 여기서 `|| echo 0` 을 쓰면 안 된다. 파일이 없으면 위에서 원문으로 떨어진다.
    hits=$({ grep -o 'read_dir(' "$scan" || true; } | wc -l)
    [ "$hits" -eq 0 ] && continue
    report+="  ${file}: ${hits}"$'\n'
    count=$((count + hits))
done <<<"$FILES"

# 훑은 수를 함께 찍는다 — 초록일 때 찍지 않으면 "안 봤다" 와 "봤는데 없다" 가 화면에서
# 같은 모양이 된다. 계산은 위(판정 불가 갈래보다 앞)에 있다.
echo "통합 테스트 타깃 ${target_count}개를 훑었다."
echo "통합 테스트 타깃의 직접 read_dir( : ${count}건 (상한 ${CAP})"
echo

if [ "$count" -gt "$CAP" ]; then
    printf '%s' "$report"
    echo
    echo "직접 순회가 늘었다: ${count} > 상한 ${CAP}."
    echo "새 순회를 tasty_doc_guards::floored_walk::walk_with_floor 로 옮겨라 — 거기서는"
    echo "하한이 인자라 빠뜨릴 수 없고, 실패문과 '하한을 내려서 통과시키지 마라' 는"
    echo "금지를 공용 함수가 만든다. 파일을 모으면 walk_with_floor, 디렉토리를 모으면"
    echo "walk_dirs_with_floor 다(뒤쪽은 하한이 모은 수가 아니라 훑은 수에 걸린다)."
    echo "상한을 올려서 통과시키지 마라 — 래칫은 한 방향으로만 돈다."
    exit 1
fi

# 수가 내려간 이유는 이 게이트가 모른다 — 원인을 단정하지 않고 갈래를 연다. 상한은
# 되돌아 올라가지 않으므로, 틀린 갈래에서 내린 한 번이 영구히 그만큼을 안 보게 만든다.
if [ "$count" -lt "$CAP" ]; then
    echo "직접 순회가 ${count} 로 상한 ${CAP} 보다 적게 나왔다."
    echo
    echo "★ 이 줄은 원인을 말하지 않는다 — 수가 내려가는 길이 셋이다."
    echo "  ㄱ 정말로 줄었다(순회를 공용 헬퍼로 옮겼다)."
    echo "  ㄴ 좌변이 반쯤 줄었다. 위의 '통합 테스트 타깃 N개' 를 직전 회차와 비교해라 —"
    echo "     판정 불가(exit 2)는 좌변이 완전히 빌 때 걸리고, 반만 준 좌변은 여기로 온다."
    echo "  ㄷ 세는 술어가 깨졌다. 이때 값은 실제보다 작고, 그 상태에서 상한을 내리면"
    echo "     다음 회차부터 진짜 회귀가 그 차이만큼 조용히 통과한다."
    echo
    echo "ㄱ 임을 확인한 뒤에만: 이 스크립트의 CAP 을 ${count} 로 내려라. 상한이 실제보다"
    echo "크면 그 차이만큼 새 순회를 조용히 받아준다 — 남는 여유가 곧 안 보는 구간이다."
    exit 1
fi
