# shellcheck shell=bash
# rpm 자동 Requires를 만드는 도구를 확인하고, 만든 rpm의 Requires가 payload ELF의 직접 의존과 맞는지 대조한다.
# build-linux.sh가 source한다.
#
# Requires는 cargo-generate-rpm --auto-req find-requires(rpm의 rpmdeps/elfdeps)가 만든다. 이 모드에는
# 대체 경로가 없다. 인자 없이 두면 cargo-generate-rpm은 빌드 머신에 find-requires가 없을 때 ldd로 전이 의존까지
# 넣는 builtin 방식으로 바뀐다. 그 결과가 빌드 머신 배포판의 soname(ICU 버전 등)에 묶여 다른 배포판에 설치되지 않았다.
# 그래서 방식은 저장소가 정하고, 결과는 elfdeps 규칙을 readelf로 따로 계산한 기대 집합과 정확히 같아야 한다.
#
# 기대 집합은 RPM 4.18.2 tools/elfdeps.c의 규칙을 따른다(릴리스 러너의 rpm 버전, docs/dev-guide/release.md).
# - ELF64 ET_EXEC·ET_DYN 파일만 본다. PT_INTERP가 있고 실행 비트가 하나도 없으면 그 파일은 Requires를 내지 않는다.
# - NEEDED s마다 s()(64bit), Version needs의 (s, v)마다 s(v)(64bit). soname은 공백만이 아니고 ".so"를 담으며
#   앞 3자가 lib·ld.·ld-·ld6인 것만 남긴다(elfdeps는 "ld64."·"ld64-"를 3자만 비교한다).
# - DT_GNU_HASH가 있고 DT_HASH가 없으면 rtld(GNU_HASH).

# rpm 생성·검사에 필요한 도구를 확인한다. $1 = find-requires 경로. 빠진 항목을 모두 알리고 1을 돌려준다.
check_rpm_tools() {
    local find_requires=$1 tool probe out missing=() broken=""
    [[ -f "$find_requires" && -x "$find_requires" ]] || missing+=("$find_requires")
    for tool in rpm rpm2cpio cpio readelf; do
        command -v "$tool" &>/dev/null || missing+=("$tool")
    done
    if [[ ${#missing[@]} -eq 0 ]]; then
        # 스크립트가 있어도 안쪽 rpmdeps가 깨졌을 수 있다. 실제 ELF 하나로 libc 의존이 나오는지 본다.
        probe=$(readlink -f "$(command -v cpio)")
        if ! out=$(printf '%s' "$probe" | "$find_requires" 2>&1); then
            broken="$find_requires failed on $probe"
        elif ! grep -qxF 'libc.so.6()(64bit)' <<<"$out"; then
            broken="$find_requires printed no libc.so.6()(64bit) for $probe"
        fi
    fi
    if [[ ${#missing[@]} -gt 0 || -n "$broken" ]]; then
        [[ ${#missing[@]} -gt 0 ]] && echo "Error: rpm packaging tools missing: ${missing[*]}" >&2
        [[ -n "$broken" ]] && echo "Error: $broken" >&2
        echo "  rpm requires are generated by $find_requires (rpmdeps) on every builder; there is no fallback." >&2
        echo "  Debian/Ubuntu: sudo apt install rpm cpio binutils   Fedora: sudo dnf install rpm-build cpio binutils" >&2
        return 1
    fi
}

# 파일이 ELF인지 첫 4바이트로 본다.
rpm_is_elf() {
    [[ "$(LC_ALL=C head -c 4 "$1" 2>/dev/null | od -An -tx1 | tr -d ' \n')" == "7f454c46" ]]
}

# 파일 모드에 실행 비트(u·g·o 중 하나)가 있는지 본다.
rpm_has_exec_bit() {
    local mode
    mode=$(stat -c '%a' "$1") || return 2
    (( (8#$mode & 8#111) != 0 ))
}

# 한 ELF 파일이 내야 할 Requires를 출력한다. readelf 실패는 경로와 함께 1을 돌려준다.
rpm_expected_requires_file() {
    local f=$1 header dynamic versions
    header=$(LC_ALL=C readelf -hlW "$f" 2>/dev/null) || { echo "Error: readelf -hl failed on $f" >&2; return 1; }
    grep -qE '^ +Class: +ELF64$' <<<"$header" || { echo "Error: $f is not ELF64; the (64bit) requires check expects ELF64" >&2; return 1; }
    grep -qE '^ +Type: +(EXEC|DYN) ' <<<"$header" || return 0
    if grep -qE '^ +INTERP ' <<<"$header" && ! rpm_has_exec_bit "$f"; then
        return 0
    fi
    dynamic=$(LC_ALL=C readelf -dW "$f" 2>/dev/null) || { echo "Error: readelf -d failed on $f" >&2; return 1; }
    versions=$(LC_ALL=C readelf -VW "$f" 2>/dev/null) || { echo "Error: readelf -V failed on $f" >&2; return 1; }
    {
        sed -n 's/.*(NEEDED).*\[\(.*\)\]$/\1/p' <<<"$dynamic" | LC_ALL=C awk '{ print $0 "\t" }'
        LC_ALL=C awk '
            /^Version needs section/ { inneed = 1; next }
            /^Version (definition|symbols) section/ { inneed = 0; next }
            inneed && match($0, /File: [^ ]+/) { file = substr($0, RSTART + 6, RLENGTH - 6); next }
            inneed && file != "" && match($0, /Name: [^ ]+/) { print file "\t" substr($0, RSTART + 6, RLENGTH - 6) }
        ' <<<"$versions"
    } | LC_ALL=C awk -F '\t' '
        {
            s = $1
            if (s !~ /[^[:space:]]/) next
            if (index(s, ".so") == 0) next
            p = substr(s, 1, 3)
            if (p != "lib" && p != "ld." && p != "ld-" && p != "ld6") next
            print s "(" $2 ")(64bit)"
        }
    '
    if grep -qE '\(GNU_HASH\)' <<<"$dynamic" && ! grep -qE '\(HASH\)' <<<"$dynamic"; then
        echo "rtld(GNU_HASH)"
    fi
}

# payload 폴더의 기대 Requires 합집합을 정렬해 출력한다. ELF가 없거나 payload 계약을 어기면 1.
# 계약: 실행 비트가 있는 파일은 모두 ELF이고(실행 스크립트 금지), ELF는 모두 실행 비트가 있다.
rpm_expected_requires() {
    local root=$1 f rel elf_count=0 rc=0 out
    out=$(
        while IFS= read -r -d '' f; do
            rel=${f#"$root"/}
            if rpm_is_elf "$f"; then
                rpm_has_exec_bit "$f" || { echo "Error: ELF without an execute bit in the payload: /$rel" >&2; exit 1; }
                rpm_expected_requires_file "$f" || exit 1
                echo "#elf"
            elif rpm_has_exec_bit "$f"; then
                echo "Error: executable non-ELF file in the payload: /$rel" >&2
                exit 1
            fi
        done < <(find "$root" -type f -print0)
    ) || rc=1
    elf_count=$(grep -cx '#elf' <<<"$out" || true)
    if [[ $rc -eq 0 && $elf_count -eq 0 ]]; then
        echo "Error: no ELF files in the payload under $root" >&2
        rc=1
    fi
    grep -vx '#elf' <<<"$out" | grep . | LC_ALL=C sort -u
    return "$rc"
}

# Cargo.toml의 [package.metadata.generate-rpm.requires] 이름을 출력한다. 값은 "*"만 지원한다(버전 조건은
# 이 대조가 표현하지 못한다). 표가 비었거나 다른 값이 있으면 1.
rpm_manual_requires() {
    LC_ALL=C awk '
        /^\[/ { intable = ($0 == "[package.metadata.generate-rpm.requires]"); next }
        !intable || /^[[:space:]]*(#|$)/ { next }
        {
            line = $0
            if (match(line, /^[[:space:]]*[A-Za-z0-9_.+-]+[[:space:]]*=[[:space:]]*"\*"[[:space:]]*$/)) {
                sub(/^[[:space:]]*/, "", line); sub(/[[:space:]]*=.*/, "", line); print line; n++
            } else {
                print "Error: unsupported rpm requires entry in Cargo.toml (only name = \"*\"): " $0 > "/dev/stderr"; bad = 1
            }
        }
        END {
            if (n == 0) { print "Error: no [package.metadata.generate-rpm.requires] entries in Cargo.toml" > "/dev/stderr"; bad = 1 }
            exit bad
        }
    ' "$1"
}

# 순수 대조. $1 = rpm -qpR 출력, $2 = 기대 자동 Requires, $3 = 수동 Requires 이름(각각 한 줄에 하나인 파일).
# rpmlib(...)는 rpm이 넣는 형식 항목이라 넘긴다. /bin/sh(cargo-generate-rpm require-sh 기본값)와 수동 이름은
# 반드시 있어야 하고, 나머지는 기대 집합과 정확히 같아야 한다. 어긋난 줄을 모두 출력하고 1을 돌려준다.
compare_rpm_requires() {
    LC_ALL=C awk -v expected_file="$2" -v manual_file="$3" '
        BEGIN {
            while ((getline line < expected_file) > 0) if (line != "") expected[line] = 1
            while ((getline line < manual_file) > 0) if (line != "") manual[line] = 1
            manual["/bin/sh"] = 1
        }
        { sub(/[[:space:]]+$/, "") }
        $0 == "" || /^rpmlib\(/ { next }
        $0 in manual { seen_manual[$0] = 1; next }
        $0 in expected { seen[$0] = 1; next }
        { print "unexpected: " $0; bad = 1 }
        END {
            for (e in expected) if (!(e in seen)) { print "missing: " e; bad = 1 }
            for (m in manual) if (!(m in seen_manual)) { print "missing: " m; bad = 1 }
            exit bad
        }
    ' "$1" | LC_ALL=C sort
    return "${PIPESTATUS[0]}"
}

# $1 = rpm -qpR 출력 파일, $2 = payload 폴더, $3 = Cargo.toml, $4 = find-requires 경로(진단용).
verify_rpm_requires_from() {
    local reqs=$1 root=$2 manifest=$3 find_requires=$4 work rc=0 entry f
    if [[ ! -s "$reqs" ]]; then
        echo "Error: the rpm has no requires at all" >&2
        return 1
    fi
    work=$(mktemp -d)
    rpm_expected_requires "$root" >"$work/expected" || rc=1
    rpm_manual_requires "$manifest" >"$work/manual" || rc=1
    if [[ $rc -eq 0 ]] && ! compare_rpm_requires "$reqs" "$work/expected" "$work/manual" >"$work/diff"; then
        echo "Error: rpm requires do not match the direct dependencies of the payload ELF files:" >&2
        sed 's/^/  /' "$work/diff" >&2
        # 기대에 없는 항목은 payload 파일마다 생성기를 다시 돌려 낸 파일을 찾는다.
        while IFS= read -r entry; do
            entry=${entry#unexpected: }
            while IFS= read -r -d '' f; do
                if printf '%s' "$f" | "$find_requires" 2>/dev/null | grep -qxF "$entry"; then
                    echo "  $entry <- /${f#"$root"/}" >&2
                fi
            done < <(find "$root" -type f -print0)
        done < <(grep '^unexpected: ' "$work/diff")
        rc=1
    fi
    if [[ $rc -eq 0 ]]; then
        echo "  rpm requires: $(grep -c . "$reqs") entries match $(grep -c . "$work/expected") expected from the payload ELF files"
    fi
    rm -rf "$work"
    return "$rc"
}

# $1 = rpm 파일, $2 = payload를 푼 폴더, $3 = Cargo.toml, $4 = find-requires 경로.
verify_rpm_requires() {
    local rpm_file=$1 reqs rc=0
    reqs=$(mktemp)
    if ! LC_ALL=C rpm -qpR "$rpm_file" >"$reqs" 2>/dev/null; then
        rm -f "$reqs"
        echo "Error: rpm -qpR failed on $rpm_file" >&2
        return 1
    fi
    verify_rpm_requires_from "$reqs" "$2" "$3" "$4" || rc=1
    rm -f "$reqs"
    return "$rc"
}
